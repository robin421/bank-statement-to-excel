#!/usr/bin/env node
/**
 * Build the legacy-URL redirect rules from src/data/legacy-redirects.mjs.
 *
 *   node scripts/gen-legacy-redirects.mjs          write public/_redirects + vercel.json "redirects"
 *   node scripts/gen-legacy-redirects.mjs --check  fail if either is stale, or (when dist/ exists)
 *                                                  if any redirected path is a page this site builds
 */
import fs from 'node:fs';
import path from 'node:path';
import { LEGACY_ORIGIN, LEGACY_BLOG_SLUGS, LEGACY_PROJECTS } from '../src/data/legacy-redirects.mjs';

const O = LEGACY_ORIGIN;
const enc = (s) => s.split('/').map((p) => encodeURIComponent(p)).join('/');

/** [from, to] pairs. `from` never has a trailing slash; splats end in /*. */
const rules = [
  ['/en', `${O}/en`],
  ['/en/*', `${O}/en/:splat`],
  ['/zh', `${O}/zh`],
  ['/zh/*', `${O}/zh/:splat`],
  ['/projects', `${O}/en/projects`],
  ...LEGACY_PROJECTS.map((p) => [`/projects/${p}`, `${O}/en/projects/${p}`]),
  ['/radar', `${O}/en/radar`],
  ['/radar/sample', `${O}/en/radar/sample`],
  ['/resume', `${O}/en/about`],
  ['/rss.xml', `${O}/rss.xml`],
  ...Object.entries(LEGACY_BLOG_SLUGS).map(([slug, to]) => [`/blog/${enc(slug)}`, `${O}${to}`]),
];

function pagesFile() {
  const lines = [
    '# GENERATED by scripts/gen-legacy-redirects.mjs from src/data/legacy-redirects.mjs. Do not edit.',
    '# Old personal-site URLs (now on blog.wattflow.net) that GSC reports as 404 on www.',
  ];
  for (const [from, to] of rules) {
    lines.push(`${from} ${to} 301`);
    if (!from.endsWith('*')) lines.push(`${from}/ ${to} 301`);
  }
  return lines.join('\n') + '\n';
}

function vercelRedirects() {
  return rules.map(([from, to]) => ({
    source: from.endsWith('/*') ? `${from.slice(0, -2)}/:splat*` : from,
    destination: to,
    permanent: true,
  }));
}

const redirectsPath = path.resolve('public/_redirects');
const vercelPath = path.resolve('vercel.json');
const vercel = JSON.parse(fs.readFileSync(vercelPath, 'utf8'));
const wantVercel = { ...vercel, redirects: vercelRedirects() };
const wantPages = pagesFile();

if (process.argv.includes('--check')) {
  const errors = [];
  if (!fs.existsSync(redirectsPath) || fs.readFileSync(redirectsPath, 'utf8') !== wantPages)
    errors.push('public/_redirects is stale — run node scripts/gen-legacy-redirects.mjs');
  if (JSON.stringify(vercel.redirects) !== JSON.stringify(wantVercel.redirects))
    errors.push('vercel.json redirects are stale — run node scripts/gen-legacy-redirects.mjs');
  const dist = path.resolve('dist');
  if (fs.existsSync(dist)) {
    for (const [from] of rules) {
      const base = decodeURIComponent(from.replace(/\/\*$/, ''));
      const hits = [path.join(dist, base), path.join(dist, base, 'index.html'), path.join(dist, `${base}.html`)];
      if (hits.some((p) => fs.existsSync(p) && p !== dist)) errors.push(`redirect source ${from} is a real page in dist/`);
    }
  }
  if (errors.length) {
    console.error(errors.join('\n'));
    process.exit(1);
  }
  console.log(`legacy-redirects: ${rules.length} rules OK`);
} else {
  fs.writeFileSync(redirectsPath, wantPages);
  fs.writeFileSync(vercelPath, JSON.stringify(wantVercel, null, 2) + '\n');
  console.log(`legacy-redirects: wrote ${rules.length} rules to public/_redirects and vercel.json`);
}
